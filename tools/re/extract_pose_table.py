"""Generate src/sim/data/pose-table.ts from the pose table in Dsj.exe.

Usage: python3 -I extract_pose_table.py <Dsj.exe> <out.ts>

The table lives in the initialised data segment (DS:0BFC, 0B0h bytes per
pose). Routine 1cb6:0d15 reads, for pose p and leg l (1..2):
  upper segment  DS:0C0C + p*0B0h + l*8   (scaled by 1.08), rate at +0CACh
  lower segment  DS:0C10 + p*0B0h + l*8   (scaled by 0.74), rate at +0CB0h
  joint k (1..9) DS:0BFC + p*0B0h + l*24h + k*4, rate at DS:0C44 + same
Values are Singles; each is written as the shortest decimal that rounds to
the same Single, so Math.fround restores it exactly.
"""

from __future__ import annotations

import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mz_image import load_mz

DATA_SEGMENT = 0x22F2
POSE_STRIDE = 0xB0
POSE_IDS = range(1, 9)
LEGS = (1, 2)
JOINTS = range(1, 10)


def shortest_single(v: float) -> str:
    for digits in range(1, 18):
        text = f"{v:.{digits}g}"
        if struct.unpack("<f", struct.pack("<f", float(text)))[0] == v:
            return text
    return repr(v)


def main() -> None:
    mz = load_mz(sys.argv[1])
    base = DATA_SEGMENT * 16

    def single(offset: int) -> float:
        return struct.unpack_from("<f", mz.image, base + offset)[0]

    lines = [
        "// Generated by tools/re/extract_pose_table.py from Dsj.exe v2.10P. Do not edit by hand.",
        "// Pose parameters of the original jumper model (docs/physics-spec.md, section on poses).",
        "",
        'import type { PoseDefinition } from "../pose";',
        "",
        "export const ORIGINAL_POSES: ReadonlyMap<number, PoseDefinition> = new Map([",
    ]
    for p in POSE_IDS:
        legs = []
        for leg in LEGS:
            o = p * POSE_STRIDE + leg * 8
            upper = (single(0x0C0C + o), single(0x0CAC + o))
            lower = (single(0x0C10 + o), single(0x0CB0 + o))
            targets = [single(0x0BFC + p * POSE_STRIDE + leg * 0x24 + k * 4) for k in JOINTS]
            rates = [single(0x0C44 + p * POSE_STRIDE + leg * 0x24 + k * 4) for k in JOINTS]
            fmt = lambda vs: "[" + ", ".join(shortest_single(v) for v in vs) + "]"
            legs.append(
                "      {\n"
                f"        upperLength: {shortest_single(upper[0])},\n"
                f"        upperRate: {shortest_single(upper[1])},\n"
                f"        lowerLength: {shortest_single(lower[0])},\n"
                f"        lowerRate: {shortest_single(lower[1])},\n"
                f"        jointTargets: {fmt(targets)},\n"
                f"        jointRates: {fmt(rates)},\n"
                "      }"
            )
        lines.append(f"  [\n    {p},\n    [\n" + ",\n".join(legs) + ",\n    ],\n  ],")
    lines.append("]);")
    with open(sys.argv[2], "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
